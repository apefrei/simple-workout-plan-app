export default function BottomNav() {
  const location = useLocation()
  const navigate = useNavigate()

  // Hide bottom nav during workout sessions
  if (location.pathname.includes('/workout')) return null

  const isActive = (path: string) => {
    if (path === '/') return location.pathname === '/' || location.pathname.startsWith('/routines')
    return location.pathname.startsWith(path)
  }

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-40 border-t border-gray-200 bg-white pb-[env(safe-area-inset-bottom)] dark:border-gray-700 dark:bg-gray-800">
      <div className="mx-auto flex max-w-lg">
        {tabs.map((tab) => {
          const active = isActive(tab.path)
          return (
            <button
              key={tab.path}
              onClick={() => {
                triggerHaptic('light')
                navigate(tab.path)
              }}
              className={`flex flex-1 flex-col items-center gap-0.5 py-2 text-sm font-medium transition-colors ${
                active
                  ? 'text-blue-600 dark:text-blue-400'
                  : 'text-gray-500 hover:text-gray-700 dark:text-gray-400 dark:hover:text-gray-200'
              }`}
            >
              {tab.icon}
              <span className="text-xs">{tab.label}</span>
            </button>
          )
        })}
      </div>
    </nav>
  )
}
